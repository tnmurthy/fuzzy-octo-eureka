// bridge.js - the operator's Buzz <-> Arunachala team bridge.
//
// Logs in to the Buzz relay as a bot (NIP-42), listens for channel messages
// that mention it, and answers only the operator. TypeSafe decides what each
// message is (router.js); handler.js answers from dashboard data or a local
// persona. Everything it calls on this machine goes to 127.0.0.1, so the
// dashboard's Cloudflare Access gate is not involved.
//
// Config: buzz-bridge/.env (gitignored). The bot's secret key is generated on
// first start and saved there.

const fs = require('fs');
const path = require('path');
const { generateSecretKey, getPublicKey, finalizeEvent } = require('nostr-tools/pure');
const { makeAuthEvent } = require('nostr-tools/nip42');
const { npubEncode } = require('nostr-tools/nip19');
const { channelFilter, shouldHandle, shouldLogSkip, replyTemplate, stripMentions } = require('./buzz-protocol');
const { createHandler } = require('./handler');
const { createTypeSafeClient } = require('./typesafe-client');
const { createLocalRouterClient } = require('./local-router-client');
const { createFallbackRouterClient } = require('./router-fallback');
const { createPendingStore } = require('./pending-store');

const ENV_FILE = path.join(__dirname, '.env');
try { process.loadEnvFile(ENV_FILE); } catch { /* no .env: rely on the environment */ }

// Own variable name: the machine already sets BUZZ_RELAY_URL=https://... for
// Buzz desktop, and NIP-42 needs the ws(s) URL in the AUTH relay tag.
const RELAY_URL = (process.env.BRIDGE_RELAY_URL || 'wss://buzz.mytestbed.tech').replace(/^http/, 'ws');
const BOT_NAME = process.env.BUZZ_BOT_NAME || 'Arunachala Team';
// The only people the bot obeys: the owner of this install (their Buzz
// pubkeys, hex). No default - each teammate's bridge obeys only them.
const OPERATORS = (process.env.BUZZ_OPERATORS || '').split(',').map(s => s.trim()).filter(Boolean);
if (!OPERATORS.length) {
  console.error('BUZZ_OPERATORS is empty in buzz-bridge/.env - set your Buzz pubkey(s); the bot obeys no one without it.');
  process.exit(1);
}
const CHANNELS = (process.env.BUZZ_BOT_CHANNELS || '').split(',').filter(Boolean);
const DASHBOARD = process.env.DASHBOARD_URL || 'http://127.0.0.1:8787';
const PROJECTS_DIR = process.env.PROJECTS_DIR || path.resolve(__dirname, '../..');
const LEDGER_FILE = path.resolve(__dirname, '../logs/typesafe-ledger.jsonl');
// Shared AI call ledger (same file server.js writes its persona calls to);
// the dashboard's team-store syncs it to Supabase when configured.
const AI_CALLS_FILE = path.resolve(__dirname, '../logs/ai-calls.jsonl');
const { recordAiCall } = require('../team-store/ai-ledger');
const onCall = (call) => recordAiCall(AI_CALLS_FILE, call);
const CHAT_TIMEOUT_MS = 120000;
const RECONNECT_MAX_MS = 60000;
const SEEN_LIMIT = 500;

function loadOrCreateSecret() {
  const hex = process.env.BUZZ_BOT_SECRET_KEY;
  if (hex && /^[0-9a-f]{64}$/.test(hex)) return Uint8Array.from(Buffer.from(hex, 'hex'));
  const sk = generateSecretKey();
  fs.appendFileSync(ENV_FILE, `\n# Generated by bridge.js - the bot's Buzz identity. Keep secret.\nBUZZ_BOT_SECRET_KEY=${Buffer.from(sk).toString('hex')}\n`);
  console.log('Generated a new bot key and saved it to buzz-bridge/.env');
  return sk;
}

const SECRET = loadOrCreateSecret();
const BOT_PUBKEY = getPublicKey(SECRET);
const now = () => Math.floor(Date.now() / 1000);

async function getJson(urlPath, timeoutMs = 10000) {
  const res = await fetch(DASHBOARD + urlPath, { signal: AbortSignal.timeout(timeoutMs) });
  if (!res.ok) throw new Error(`${urlPath} HTTP ${res.status}`);
  return res.json();
}

const dashboard = {
  telemetry: () => getJson('/api/telemetry'),
  runs: async () => (await getJson('/api/runs')).runs || [],
  chat: async (persona, message) => {
    const res = await fetch(DASHBOARD + '/api/agent/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ agent: persona, message }),
      signal: AbortSignal.timeout(CHAT_TIMEOUT_MS),
    });
    const body = await res.json();
    if (!body.ok) throw new Error(body.error || `chat HTTP ${res.status}`);
    return body.reply.trim();
  },
};

function listRepos() {
  return fs.readdirSync(PROJECTS_DIR, { withFileTypes: true })
    .filter(d => d.isDirectory() && !d.name.includes('--') && fs.existsSync(path.join(PROJECTS_DIR, d.name, '.git')))
    .map(d => d.name);
}

// Dispatch: a non-risky 'dispatch' decision (handler.js) calls n8n's webhook,
// which runs orchestration/agent-dispatch.sh via /api/dispatch/run and polls
// /api/runs for completion. n8n responds to the webhook immediately with the
// run id (so the operator gets an ack without waiting for the run), then -
// once the run finishes - POSTs to this process's own /notify listener with
// {runId, text}, which is published back into the original thread. The
// event that triggered a run is kept in logs/pending-dispatch.json
// (pending-store.js), so a bridge restart mid-run still gets the reply.
const N8N_DISPATCH_WEBHOOK_URL = process.env.N8N_DISPATCH_WEBHOOK_URL || 'http://127.0.0.1:5678/webhook/buzz-dispatch';
const NOTIFY_PORT = Number(process.env.BRIDGE_NOTIFY_PORT) || 3100;
const DISPATCH_TRIGGER_TIMEOUT_MS = 15000;
const pendingDispatch = createPendingStore({ file: path.resolve(__dirname, '../logs/pending-dispatch.json') });
let currentPublish = null;
let activeEvent = null; // the event currently being handled, for registerPending to key off

const dispatch = {
  trigger: async ({ agent, repo, task }) => {
    const res = await fetch(N8N_DISPATCH_WEBHOOK_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ agent, repo, task }),
      signal: AbortSignal.timeout(DISPATCH_TRIGGER_TIMEOUT_MS),
    });
    const body = await res.json().catch(() => ({}));
    if (!res.ok || !body.runId) throw new Error(body.error || `n8n webhook HTTP ${res.status}`);
    return { runId: body.runId };
  },
  registerPending: (runId) => pendingDispatch.set(runId, activeEvent),
};

function startNotifyServer() {
  require('http').createServer((req, res) => {
    if (req.method !== 'POST' || req.url.split('?')[0] !== '/notify') {
      res.writeHead(404); return res.end();
    }
    let body = '';
    req.on('data', (c) => { body += c; });
    req.on('end', () => {
      let payload;
      try { payload = JSON.parse(body || '{}'); } catch { payload = {}; }
      const { runId, text } = payload;
      const event = pendingDispatch.take(runId);
      if (!event) {
        res.writeHead(404, { 'Content-Type': 'application/json' });
        return res.end(JSON.stringify({ ok: false, error: `no pending dispatch for run ${runId}` }));
      }
      if (currentPublish) currentPublish(replyTemplate(event, text || `Run ${runId} finished.`, now()));
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ ok: true }));
    });
  }).listen(NOTIFY_PORT, '127.0.0.1', () => console.log(`Notify listener on 127.0.0.1:${NOTIFY_PORT}/notify`));
}

// Routing brain: local Ollama by default (free, private, no API key); set
// BUZZ_ROUTER=typesafe (with TYPESAFE_API_KEY) to use the cloud router
// instead. Either way, persona replies (handler.js's 'persona' action) and
// the fallback-on-error path always go through the local Ollama personas
// via dashboard.chat - only the routing judgment (what kind of message is
// this, which persona/repo/executor fits) changes client.
//
// 'local' is itself a fallback chain, not one model: the primary model gets
// a short budget (LOCAL_ROUTER_TIMEOUT_MS, default 25s) so a slow/stuck
// request degrades to a faster, smaller model (LOCAL_ROUTER_FALLBACK_MODEL,
// default qwen2.5-coder:3b) instead of making the operator wait out a long
// single timeout. If every local stage fails, handler.js's own catch still
// falls back one more level, to a plain PO persona chat reply.
const ROUTER_MODE = process.env.BUZZ_ROUTER || (process.env.TYPESAFE_API_KEY ? 'typesafe' : 'local');
const LOCAL_ROUTER_MODEL = process.env.LOCAL_ROUTER_MODEL || 'gemma3:4b';
const LOCAL_ROUTER_FALLBACK_MODEL = process.env.LOCAL_ROUTER_FALLBACK_MODEL || 'qwen2.5-coder:3b';
const LOCAL_ROUTER_TIMEOUT_MS = Number(process.env.LOCAL_ROUTER_TIMEOUT_MS) || 25000;
const LOCAL_ROUTER_FALLBACK_TIMEOUT_MS = Number(process.env.LOCAL_ROUTER_FALLBACK_TIMEOUT_MS) || 20000;
const router = ROUTER_MODE === 'local'
  ? createFallbackRouterClient([
      {
        label: LOCAL_ROUTER_MODEL,
        client: createLocalRouterClient({
          host: process.env.LOCAL_ROUTER_HOST,
          port: Number(process.env.LOCAL_ROUTER_PORT) || undefined,
          model: LOCAL_ROUTER_MODEL,
          timeoutMs: LOCAL_ROUTER_TIMEOUT_MS,
          onCall,
        }),
      },
      {
        label: LOCAL_ROUTER_FALLBACK_MODEL,
        client: createLocalRouterClient({
          host: process.env.LOCAL_ROUTER_HOST,
          port: Number(process.env.LOCAL_ROUTER_PORT) || undefined,
          model: LOCAL_ROUTER_FALLBACK_MODEL,
          timeoutMs: LOCAL_ROUTER_FALLBACK_TIMEOUT_MS,
          onCall,
        }),
      },
    ])
  : createTypeSafeClient({
      apiKey: process.env.TYPESAFE_API_KEY,
      ledgerFile: LEDGER_FILE,
      dailyCap: Number(process.env.TYPESAFE_DAILY_CAP) || undefined,
      onCall,
    });

const handle = createHandler({
  typesafe: router,
  dashboard,
  dispatch,
  repos: listRepos,
});

function connect(startedAt, attempt = 0) {
  const ws = new WebSocket(RELAY_URL);
  const seen = new Set();
  let authed = false;

  const send = (msg) => ws.send(JSON.stringify(msg));
  const publish = (template) => {
    const event = finalizeEvent(template, SECRET);
    send(['EVENT', event]);
    return event;
  };
  currentPublish = publish;

  ws.addEventListener('open', () => console.log(`Connected to ${RELAY_URL} as ${npubEncode(BOT_PUBKEY)}`));

  ws.addEventListener('message', async ({ data }) => {
    let msg;
    try { msg = JSON.parse(data); } catch { return; }
    const [type] = msg;

    if (type === 'AUTH') {
      send(['AUTH', finalizeEvent(makeAuthEvent(RELAY_URL, msg[1]), SECRET)]);
      return;
    }
    if (type === 'OK' && !authed) {
      if (!msg[2]) { console.error(`Relay refused login: ${msg[3]}`); return ws.close(); }
      authed = true;
      attempt = 0;
      console.log('Logged in to the relay');
      // Deliberately a plain member, not a Buzz "agent": the desktop runs an
      // agent-authorization preflight on mentions of bot-flagged accounts
      // (for agents it manages itself) and refuses to send to this one.
      publish({ kind: 0, created_at: now(), tags: [], content: JSON.stringify({ name: BOT_NAME, about: 'Arunachala AI team bridge. Mention me with a question or task.' }) });
      for (const ch of CHANNELS) publish({ kind: 9000, created_at: now(), tags: [['h', ch], ['p', BOT_PUBKEY], ['role', 'member']], content: '' });
      if (!CHANNELS.length) console.error('BUZZ_BOT_CHANNELS is empty - the bot will not hear any messages');
      else send(['REQ', 'channels', channelFilter(CHANNELS, startedAt)]);
      return;
    }
    if (type === 'OK' && !msg[2]) { console.error(`Relay rejected event ${msg[1].slice(0, 8)}: ${msg[3]}`); return; }
    if (type === 'CLOSED') { console.error(`Subscription closed by relay: ${msg[2]}`); return; }
    if (type !== 'EVENT') return;

    const event = msg[2];
    if (seen.has(event.id)) return;
    seen.add(event.id);
    if (seen.size > SEEN_LIMIT) seen.delete(seen.values().next().value);

    const verdict = shouldHandle(event, { botPubkey: BOT_PUBKEY, operators: OPERATORS, startedAt });
    if (!verdict.ok) {
      if (shouldLogSkip(event, verdict, { operators: OPERATORS })) {
        console.log(`Skipped ${event.id.slice(0, 8)}: ${verdict.reason}`);
      }
      return;
    }

    const text = stripMentions(event.content, BOT_NAME);
    console.log(`Operator: ${text}`);
    let reply;
    activeEvent = event;
    try {
      reply = await handle({ text, thread: [], log: (d) => console.log(`Decision: ${JSON.stringify(d)}`) });
    } catch (err) {
      console.error(`Handler failed: ${err.message}`);
      reply = `Sorry - that failed: ${err.message}`;
    } finally {
      activeEvent = null;
    }
    if (reply) publish(replyTemplate(event, reply, now()));
  });

  ws.addEventListener('close', () => {
    const delay = Math.min(RECONNECT_MAX_MS, 1000 * 2 ** attempt);
    console.error(`Relay connection closed; reconnecting in ${delay / 1000}s`);
    setTimeout(() => connect(startedAt, attempt + 1), delay);
  });
  ws.addEventListener('error', (e) => console.error(`Relay connection error: ${e.message || 'unknown'}`));
}

if (ROUTER_MODE === 'typesafe' && !process.env.TYPESAFE_API_KEY) console.error('TYPESAFE_API_KEY is not set - every message will fall back to the PO');
console.log(`Router: ${ROUTER_MODE}${ROUTER_MODE === 'local' ? ` (${LOCAL_ROUTER_MODEL} -> ${LOCAL_ROUTER_FALLBACK_MODEL} via Ollama)` : ''} | Operators: ${OPERATORS.map(p => p.slice(0, 8)).join(', ')} | repos: ${listRepos().join(', ')}`);

// Weekly digest: one bridge per team posts /api/digest to its channels
// (BUZZ_DIGEST=true - off by default, or every teammate's bot would post the
// same team digest). Checked hourly; posts Monday 09:00 IST unless
// BUZZ_DIGEST_WEEKDAY (0-6, 0 = Sunday) / BUZZ_DIGEST_HOUR say otherwise.
const { isDigestDue } = require('../digest');
const DIGEST_STATE_FILE = path.resolve(__dirname, '../logs/digest-state.json');
const DIGEST_CHECK_MS = 60 * 60 * 1000;
const digestSchedule = {
  weekday: Number(process.env.BUZZ_DIGEST_WEEKDAY ?? 1),
  hour: Number(process.env.BUZZ_DIGEST_HOUR ?? 9),
};

async function postDigestIfDue() {
  if (!currentPublish || !CHANNELS.length) return;
  let state = {};
  try { state = JSON.parse(fs.readFileSync(DIGEST_STATE_FILE, 'utf8')); } catch { /* never posted */ }
  if (!isDigestDue(Date.now(), state.lastPosted, digestSchedule)) return;
  try {
    const { text } = await getJson('/api/digest', 30000);
    for (const ch of CHANNELS) currentPublish({ kind: 9, created_at: now(), content: text, tags: [['h', ch]] });
    fs.writeFileSync(DIGEST_STATE_FILE, JSON.stringify({ lastPosted: new Date().toISOString() }));
    console.log('Posted the weekly digest');
  } catch (err) {
    console.error(`Weekly digest failed: ${err.message}`); // retried next hour
  }
}

startNotifyServer();
connect(now());
if (process.env.BUZZ_DIGEST === 'true') setInterval(postDigestIfDue, DIGEST_CHECK_MS);
