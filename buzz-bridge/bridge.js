// bridge.js - the operator's Buzz <-> Arunachala team bridge.
//
// Logs in to the Buzz relay as a bot (NIP-42), listens for channel messages
// that mention it, and answers only the operator. TypeSafe decides what each
// message is (router.js); handler.js answers from dashboard data or a local
// persona. Everything it calls on this machine goes to 127.0.0.1, so the
// dashboard's Cloudflare Access gate is not involved.
//
// Config: buzz-bridge/.env (gitignored). The bot's secret key is generated on
// first start and saved there.

const fs = require('fs');
const path = require('path');
const { generateSecretKey, getPublicKey, finalizeEvent } = require('nostr-tools/pure');
const { makeAuthEvent } = require('nostr-tools/nip42');
const { npubEncode } = require('nostr-tools/nip19');
const { channelFilter, shouldHandle, replyTemplate, stripMentions } = require('./buzz-protocol');
const { createHandler } = require('./handler');
const { createTypeSafeClient } = require('./typesafe-client');

const ENV_FILE = path.join(__dirname, '.env');
try { process.loadEnvFile(ENV_FILE); } catch { /* no .env: rely on the environment */ }

// Own variable name: the machine already sets BUZZ_RELAY_URL=https://... for
// Buzz desktop, and NIP-42 needs the ws(s) URL in the AUTH relay tag.
const RELAY_URL = (process.env.BRIDGE_RELAY_URL || 'wss://buzz.mytestbed.tech').replace(/^http/, 'ws');
const BOT_NAME = process.env.BUZZ_BOT_NAME || 'Arunachala Team';
// The only people the bot obeys: the relay owner identity (see CLAUDE.md) and
// the operator's Buzz desktop identity, which until 2026-10-20 doubled as the
// relay's signing key.
const OPERATORS = (process.env.BUZZ_OPERATORS || [
  '768ee3b1eccb49856271187b66d3095b70bb23d3fa883a63183c5b7f3c5235cd',
  'bd11c441f791cd9c2f390f435986e9c7a66b6d8ba469e22470543e6424080e84',
].join(',')).split(',');
const CHANNELS = (process.env.BUZZ_BOT_CHANNELS || '').split(',').filter(Boolean);
const DASHBOARD = process.env.DASHBOARD_URL || 'http://127.0.0.1:8787';
const PROJECTS_DIR = process.env.PROJECTS_DIR || path.resolve(__dirname, '../..');
const LEDGER_FILE = path.resolve(__dirname, '../logs/typesafe-ledger.jsonl');
const CHAT_TIMEOUT_MS = 120000;
const RECONNECT_MAX_MS = 60000;
const SEEN_LIMIT = 500;

function loadOrCreateSecret() {
  const hex = process.env.BUZZ_BOT_SECRET_KEY;
  if (hex && /^[0-9a-f]{64}$/.test(hex)) return Uint8Array.from(Buffer.from(hex, 'hex'));
  const sk = generateSecretKey();
  fs.appendFileSync(ENV_FILE, `\n# Generated by bridge.js - the bot's Buzz identity. Keep secret.\nBUZZ_BOT_SECRET_KEY=${Buffer.from(sk).toString('hex')}\n`);
  console.log('Generated a new bot key and saved it to buzz-bridge/.env');
  return sk;
}

const SECRET = loadOrCreateSecret();
const BOT_PUBKEY = getPublicKey(SECRET);
const now = () => Math.floor(Date.now() / 1000);

async function getJson(urlPath, timeoutMs = 10000) {
  const res = await fetch(DASHBOARD + urlPath, { signal: AbortSignal.timeout(timeoutMs) });
  if (!res.ok) throw new Error(`${urlPath} HTTP ${res.status}`);
  return res.json();
}

const dashboard = {
  telemetry: () => getJson('/api/telemetry'),
  runs: async () => (await getJson('/api/runs')).runs || [],
  chat: async (persona, message) => {
    const res = await fetch(DASHBOARD + '/api/agent/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ agent: persona, message }),
      signal: AbortSignal.timeout(CHAT_TIMEOUT_MS),
    });
    const body = await res.json();
    if (!body.ok) throw new Error(body.error || `chat HTTP ${res.status}`);
    return body.reply.trim();
  },
};

function listRepos() {
  return fs.readdirSync(PROJECTS_DIR, { withFileTypes: true })
    .filter(d => d.isDirectory() && !d.name.includes('--') && fs.existsSync(path.join(PROJECTS_DIR, d.name, '.git')))
    .map(d => d.name);
}

const handle = createHandler({
  typesafe: createTypeSafeClient({
    apiKey: process.env.TYPESAFE_API_KEY,
    ledgerFile: LEDGER_FILE,
    dailyCap: Number(process.env.TYPESAFE_DAILY_CAP) || undefined,
  }),
  dashboard,
  repos: listRepos,
});

function connect(startedAt, attempt = 0) {
  const ws = new WebSocket(RELAY_URL);
  const seen = new Set();
  let authed = false;

  const send = (msg) => ws.send(JSON.stringify(msg));
  const publish = (template) => {
    const event = finalizeEvent(template, SECRET);
    send(['EVENT', event]);
    return event;
  };

  ws.addEventListener('open', () => console.log(`Connected to ${RELAY_URL} as ${npubEncode(BOT_PUBKEY)}`));

  ws.addEventListener('message', async ({ data }) => {
    let msg;
    try { msg = JSON.parse(data); } catch { return; }
    const [type] = msg;

    if (type === 'AUTH') {
      send(['AUTH', finalizeEvent(makeAuthEvent(RELAY_URL, msg[1]), SECRET)]);
      return;
    }
    if (type === 'OK' && !authed) {
      if (!msg[2]) { console.error(`Relay refused login: ${msg[3]}`); return ws.close(); }
      authed = true;
      attempt = 0;
      console.log('Logged in to the relay');
      // Deliberately a plain member, not a Buzz "agent": the desktop runs an
      // agent-authorization preflight on mentions of bot-flagged accounts
      // (for agents it manages itself) and refuses to send to this one.
      publish({ kind: 0, created_at: now(), tags: [], content: JSON.stringify({ name: BOT_NAME, about: 'Arunachala AI team bridge. Mention me with a question or task.' }) });
      for (const ch of CHANNELS) publish({ kind: 9000, created_at: now(), tags: [['h', ch], ['p', BOT_PUBKEY], ['role', 'member']], content: '' });
      if (!CHANNELS.length) console.error('BUZZ_BOT_CHANNELS is empty - the bot will not hear any messages');
      else send(['REQ', 'channels', channelFilter(CHANNELS, startedAt)]);
      return;
    }
    if (type === 'OK' && !msg[2]) { console.error(`Relay rejected event ${msg[1].slice(0, 8)}: ${msg[3]}`); return; }
    if (type === 'CLOSED') { console.error(`Subscription closed by relay: ${msg[2]}`); return; }
    if (type !== 'EVENT') return;

    const event = msg[2];
    if (seen.has(event.id)) return;
    seen.add(event.id);
    if (seen.size > SEEN_LIMIT) seen.delete(seen.values().next().value);

    const verdict = shouldHandle(event, { botPubkey: BOT_PUBKEY, operators: OPERATORS, startedAt });
    if (!verdict.ok) {
      // The channel subscription sees every message; only log the interesting skips.
      if (!['bot not mentioned', 'own message'].includes(verdict.reason)) {
        console.log(`Skipped ${event.id.slice(0, 8)}: ${verdict.reason}`);
      }
      return;
    }

    const text = stripMentions(event.content, BOT_NAME);
    console.log(`Operator: ${text}`);
    let reply;
    try {
      reply = await handle({ text, thread: [], log: (d) => console.log(`Decision: ${JSON.stringify(d)}`) });
    } catch (err) {
      console.error(`Handler failed: ${err.message}`);
      reply = `Sorry - that failed: ${err.message}`;
    }
    if (reply) publish(replyTemplate(event, reply, now()));
  });

  ws.addEventListener('close', () => {
    const delay = Math.min(RECONNECT_MAX_MS, 1000 * 2 ** attempt);
    console.error(`Relay connection closed; reconnecting in ${delay / 1000}s`);
    setTimeout(() => connect(startedAt, attempt + 1), delay);
  });
  ws.addEventListener('error', (e) => console.error(`Relay connection error: ${e.message || 'unknown'}`));
}

if (!process.env.TYPESAFE_API_KEY) console.error('TYPESAFE_API_KEY is not set - every message will fall back to the PO');
console.log(`Operators: ${OPERATORS.map(p => p.slice(0, 8)).join(', ')} | repos: ${listRepos().join(', ')}`);
connect(now());
